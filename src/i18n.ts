/** Préfixe une route interne avec la langue : localePath("ar", "/parfums") => "/ar/parfums" */
export function localePath(locale: Locale, path = "/"): string {
  const clean = path === "/" ? "" : path.startsWith("/") ? path : `/${path}`;
  return `/${locale}${clean}`;
}

